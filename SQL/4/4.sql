

-- 1. WAQTD NUMBER OF EMPLOYEES GETTING SALARY LESS THAN 2000
--    IN DEPTNO 10

SELECT COUNT(*)
FROM emp
WHERE sal < 2000
AND deptno = 10;


-- 2. WAQTD TOTAL SALARY NEEDED TO PAY EMPLOYEES
--    WORKING AS CLERK

SELECT SUM(sal) AS total_salary
FROM emp
WHERE job = 'CLERK';


-- 3. WAQTD AVERAGE SALARY NEEDED TO PAY ALL EMPLOYEES

SELECT AVG(sal) AS average_salary
FROM emp;


-- 4. WAQTD NUMBER OF EMPLOYEES HAVING 'A'
--    AS THEIR FIRST CHARACTER

SELECT COUNT(*)
FROM emp
WHERE ename LIKE 'A%';


-- 5. WAQTD NUMBER OF EMPLOYEES WORKING
--    AS CLERK OR MANAGER

SELECT COUNT(*)
FROM emp
WHERE job IN ('CLERK', 'MANAGER');


-- 6. WAQTD TOTAL SALARY NEEDED TO PAY
--    EMPLOYEES HIRED IN FEB

SELECT SUM(sal) AS total_salary
FROM emp
WHERE EXTRACT(MONTH FROM hiredate) = 2;


-- 7. WAQTD NUMBER OF EMPLOYEES REPORTING TO 7839 (MGR)

SELECT COUNT(*)
FROM emp
WHERE mgr = 7839;


-- 8. WAQTD NUMBER OF EMPLOYEES GETTING COMMISSION
--    IN DEPTNO 30

SELECT COUNT(*)
FROM emp
WHERE comm IS NOT NULL
AND deptno = 30;


-- 9. WAQTD AVG SAL, TOTAL SAL, NUMBER OF EMPS AND
--    MAXIMUM SALARY GIVEN TO EMPLOYEES WORKING AS PRESIDENT

SELECT AVG(sal) AS average_salary, SUM(sal) AS total_salary,
    COUNT(*) AS number_of_employees,
    MAX(sal) AS maximum_salary
FROM emp
WHERE job = 'PRESIDENT';


-- 10. WAQTD NUMBER OF EMPLOYEES HAVING 'A' IN THEIR NAMES

SELECT COUNT(*)
FROM emp
WHERE ename LIKE '%A%';


-- 11. WAQTD NUMBER OF EMPS AND TOTAL SALARY NEEDED
--     TO PAY THE EMPLOYEES WHO HAVE 2 CONSECUTIVE L's
--     IN THEIR NAMES

SELECT COUNT(*) AS number_of_employees, SUM(sal) AS total_salary
FROM emp
WHERE ename LIKE '%LL%';


-- 12. WAQTD NUMBER OF DEPARTMENTS PRESENT
--     IN EMPLOYEE TABLE

SELECT COUNT(DISTINCT deptno) AS number_of_departments
FROM emp;


-- 13. WAQTD NUMBER OF EMPLOYEES HAVING CHARACTER '_'
--     IN THEIR NAMES

SELECT COUNT(*)
FROM emp
WHERE ename LIKE '%\_%' ESCAPE '\';


-- 14. WAQTD NUMBER OF EMPLOYEES HAVING ATLEAST
--     2 PERCENTILES IN THEIR NAMES
--


SELECT COUNT(*)
FROM emp
WHERE ename LIKE '%\%%\%%' ESCAPE '\';


-- 15. WAQTD TOTAL SALARY GIVEN TO EMPLOYEES
--     WORKING AS CLERK IN DEPT 30

SELECT SUM(sal) AS total_salary
FROM emp
WHERE job = 'CLERK'
AND deptno = 30;


-- 16. WAQTD MAXIMUM SALARY GIVEN TO THE EMPLOYEES
--     WORKING AS ANALYST

SELECT MAX(sal) AS maximum_salary
FROM emp
WHERE job = 'ANALYST';


-- 17. WAQTD NUMBER OF DISTINCT SALARIES
--     PRESENT IN EMPLOYEE TABLE

SELECT COUNT(DISTINCT sal) AS distinct_salaries
FROM emp;


-- 18. WAQTD NUMBER OF JOBS PRESENT IN EMPLOYEE TABLE

SELECT COUNT(DISTINCT job) AS number_of_jobs
FROM emp;


-- 19. WAQTD AVG SALARY GIVEN TO THE CLERK

SELECT AVG(sal) AS average_salary
FROM emp
WHERE job = 'CLERK';


-- 20. WAQTD MINIMUM SALARY GIVEN TO THE EMPLOYEES
--     WHO WORK IN DEPT 10 AS MANAGER OR A CLERK

SELECT MIN(sal) AS minimum_salary
FROM emp
WHERE deptno = 10
AND job IN ('MANAGER', 'CLERK');


























