-- 14) LIST ALL THE EMPLOYEES WITH ANNUAL SALARY
-- EXCEPT THOSE WHO ARE WORKING IN DEPT 30

SELECT *, sal * 12 AS annual_salary
FROM emp
WHERE deptno NOT IN (30);


-- 15) LIST THE EMPLOYEES WHOSE NAME DOES NOT END
-- WITH 'ES' OR 'R'

SELECT *
FROM emp
WHERE ename NOT LIKE '%ES'
AND ename NOT LIKE '%R';


-- 16) LIST ALL THE EMPLOYEES WHO ARE HAVING
-- REPORTING MANAGERS IN DEPT 10 ALONG WITH
-- 10% HIKE IN SALARY

SELECT *, sal * 0.10 AS hike_amount, sal * 1.10 AS hike_salary
FROM emp
WHERE mgr IS NOT NULL
AND deptno = 10;


-- 17) DISPLAY ALL THE EMPLOYEE WHO ARE SALESMAN'S
-- HAVING 'E' AS THE LAST BUT ONE CHARACTER IN ENAME
-- BUT SALARY HAVING EXACTLY 4 CHARACTER

SELECT *
FROM emp
WHERE job = 'SALESMAN'
AND ename LIKE '%E_'
AND CAST(sal AS VARCHAR) LIKE '____';


-- 18) DISPLAY ALL THE EMPLOYEE WHO ARE JOINED
-- AFTER YEAR 81

SELECT *
FROM emp
WHERE hiredate >= DATE '1982-01-01';


-- 19) DISPLAY ALL THE EMPLOYEE WHO ARE JOINED IN FEB

SELECT *
FROM emp
WHERE EXTRACT(MONTH FROM hiredate) = 2;


-- 20) LIST THE EMPLOYEES WHO ARE NOT WORKING AS
-- MANAGERS AND CLERKS IN DEPT 10 AND 20 WITH A
-- SALARY IN THE RANGE OF 1000 TO 3000

SELECT *
FROM emp
WHERE job NOT IN ('MANAGER', 'CLERK')
AND deptno IN (10, 20)
AND sal BETWEEN 1000 AND 3000;


































