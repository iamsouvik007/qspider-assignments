

-- 1) LIST ALL THE EMPLOYEES WHOSE COMMISSION IS NULL

SELECT *
FROM emp
WHERE comm IS NULL;


-- 2) LIST ALL THE EMPLOYEES WHO DON'T HAVE A REPORTING MANAGER

SELECT *
FROM emp
WHERE mgr IS NULL;


-- 3) LIST ALL THE SALESMEN IN DEPT 30

SELECT *
FROM emp
WHERE job = 'SALESMAN'
AND deptno = 30;


-- 4) LIST ALL THE SALESMEN IN DEPT NUMBER 30 AND
-- HAVING SALARY GREATER THAN 1500

SELECT *
FROM emp
WHERE job = 'SALESMAN'
AND deptno = 30
AND sal > 1500;


-- 5) LIST ALL THE EMPLOYEES WHOSE NAME STARTS WITH 'S' OR 'A'

SELECT *
FROM emp
WHERE ename LIKE 'S%'
OR ename LIKE 'A%';

