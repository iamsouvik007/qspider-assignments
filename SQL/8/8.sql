CREATE TABLE dept (
    deptno INTEGER PRIMARY KEY,
    dname  VARCHAR(14) NOT NULL,
    loc    VARCHAR(13)
);

CREATE TABLE emp (
    empno    INTEGER PRIMARY KEY,
    ename    VARCHAR(10) NOT NULL,
    job      VARCHAR(9),
    mgr      INTEGER,
    hiredate DATE,
    sal      NUMERIC(7,2),
    comm     NUMERIC(7,2),
    deptno   INTEGER,
    CONSTRAINT fk_emp_dept
        FOREIGN KEY (deptno)
        REFERENCES dept(deptno)
);

